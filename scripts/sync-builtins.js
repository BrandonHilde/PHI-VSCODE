// Regenerates src/builtins.generated.ts from the compiler's table of built-in functions
// (Compiler/Phi.Compiler/Semantics/Builtins.cs), so hovers, completions and signature help
// always match what the compiler accepts.
//
//   node scripts/sync-builtins.js [path/to/PHI]      (default: ../../Libraries/PHI or $PHI_ROOT)

const fs = require('fs');
const path = require('path');

const root = process.argv[2] || process.env.PHI_ROOT || path.resolve(__dirname, '../../../Libraries/PHI');
const source = path.join(root, 'Compiler/Phi.Compiler/Semantics/Builtins.cs');
const out = path.resolve(__dirname, '../src/builtins.generated.ts');

if (!fs.existsSync(source)) {
    console.error(`can't find ${source}; pass the PHI folder as an argument`);
    process.exit(1);
}

const text = fs.readFileSync(source, 'utf8');

// the body of each `new() { ... }` initializer, with nested braces balanced
function initializers(section) {
    const bodies = [];
    const re = /new\(\)\s*\{/g;
    let m;
    while ((m = re.exec(section))) {
        let depth = 1;
        let i = re.lastIndex;
        for (; i < section.length && depth > 0; i++) {
            if (section[i] === '"') { i = section.indexOf('"', i + 1); continue; }
            if (section[i] === '{') depth++;
            else if (section[i] === '}') depth--;
        }
        bodies.push(section.slice(re.lastIndex, i - 1));
        re.lastIndex = i;
    }
    return bodies;
}

const str = (body, name) => (body.match(new RegExp(`\\b${name}\\s*=\\s*"((?:[^"\\\\]|\\\\.)*)"`)) || [])[1];
const strs = (body, name) => {
    const m = body.match(new RegExp(`\\b${name}\\s*=\\s*new\\[\\]\\s*\\{([^}]*)\\}`));
    return m ? [...m[1].matchAll(/"([^"]*)"/g)].map(x => x[1]) : [];
};
const ints = (body, name) => {
    const m = body.match(new RegExp(`\\b${name}\\s*=\\s*new\\[\\]\\s*\\{([^}]*)\\}`));
    return m ? m[1].split(',').map(s => parseInt(s, 10)).filter(n => !isNaN(n)) : [];
};

function section(startMarker) {
    const start = text.indexOf(startMarker);
    if (start < 0) throw new Error(`${startMarker} not found in Builtins.cs`);
    const end = text.indexOf('};', start);
    return text.slice(start, end);
}

const functions = initializers(section('Functions =')).map(body => ({
    name: str(body, 'Name'),
    aliases: strs(body, 'Aliases'),
    parameters: strs(body, 'Parameters'),
    textParameters: ints(body, 'TextParameters'),
    returns: /\bReturns\s*=\s*true/.test(body),
    onlyIn: (body.match(/\bOnlyIn\s*=\s*UnitKind\.(\w+)/) || [])[1] || null,
    description: str(body, 'Description') || '',
}));

const hooks = initializers(section('Hooks =')).map(body => ({
    name: str(body, 'Name'),
    description: str(body, 'Description') || '',
}));

const colors = [...section('Constants =').matchAll(/\["Colors\.(\w+)"\]\s*=\s*(0x[0-9A-Fa-f]+|\d+)/g)]
    .map(m => ({ name: m[1], value: Number(m[2]) }));

if (functions.length < 10 || hooks.length === 0 || colors.length !== 16)
    throw new Error(`unexpected Builtins.cs layout: ${functions.length} functions, ${hooks.length} hooks, ${colors.length} colors`);

const header = `// Generated by scripts/sync-builtins.js from ${path.relative(root, source).replace(/\\/g, '/')}.\n` +
    `// Don't edit by hand: run \`npm run sync-builtins\` after the compiler's built-ins change.\n\n`;

const body =
    `export interface BuiltinFunction {\n` +
    `    name: string;\n    aliases: string[];\n    parameters: string[];\n` +
    `    /** indexes of parameters that take text (a str or ptr<u8>) */\n    textParameters: number[];\n` +
    `    returns: boolean;\n    /** null when it works in every kind of program */\n    onlyIn: string | null;\n` +
    `    description: string;\n}\n\n` +
    `export interface BuiltinHook { name: string; description: string; }\n\n` +
    `export interface BuiltinColor { name: string; value: number; }\n\n` +
    `export const builtinFunctions: BuiltinFunction[] = ${JSON.stringify(functions, null, 4)};\n\n` +
    `export const builtinHooks: BuiltinHook[] = ${JSON.stringify(hooks, null, 4)};\n\n` +
    `export const builtinColors: BuiltinColor[] = ${JSON.stringify(colors, null, 4)};\n`;

fs.writeFileSync(out, header + body);
console.log(`wrote ${path.relative(process.cwd(), out)}: ${functions.length} functions, ${hooks.length} hooks, ${colors.length} colors`);
